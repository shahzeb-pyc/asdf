"use client";

import React from "react";
import { HeartIcon, PauseIcon, PlayIcon } from "lucide-react";

import {
  MOCK_PROMPT_CARDS,
  type MockPromptCard,
} from "@/components/prompts/prompt-mock-data";

/**
 * Mock cards grid — B design, cleaner final-card layout, with the
 * seven approved card upgrades.
 *
 * Uniform card size with a fixed preview height (h-60): preview
 * media is centred with object-cover, so vertical previews are
 * cropped to that height instead of cut off at the top. Preview
 * media is in-repo MOCK/DEMO media (Pillow stills animated with
 * ffmpeg, in /public/prompt-previews/) — it is NOT a real
 * generation, NOT claimed as generated by Dola AI, Veo 3, or
 * Google Flow, and NOT copied or hotlinked from any researched
 * site. Hovering a preview plays its video muted; leaving stops
 * it. Tapping the play control plays/pauses without opening the
 * detail section. Cards lift slightly and gain a thin gold border
 * on hover (tokens only).
 *
 * Clicking a card (anywhere except the play control and the
 * favourite heart) opens the dedicated section below, showing that
 * card's mock master prompt and how-to steps. The heart toggles
 * saved/unsaved as LOCAL UI state only — no backend, no
 * persistence across reload. Cards carry NO master prompt text
 * and NO how-to steps on the card itself, and NO share button,
 * rating stars, or other card buttons beyond play and heart.
 * Copied counts shown here are the mock data's layout
 * placeholders, not real usage.
 *
 * Design-system primitives + tokens only: no literal colours, no
 * inline styles.
 */
export function PromptMockCardGrid() {
  const [selected, setSelected] = React.useState<MockPromptCard | null>(null);
  const [favourites, setFavourites] = React.useState<ReadonlySet<string>>(
    new Set(),
  );
  const [playing, setPlaying] = React.useState<ReadonlySet<string>>(new Set());
  const videoRefs = React.useRef<Record<string, HTMLVideoElement | null>>({});

  const toggleFavourite = (title: string) => {
    setFavourites((previous) => {
      const next = new Set(previous);
      if (next.has(title)) {
        next.delete(title);
      } else {
        next.add(title);
      }
      return next;
    });
  };

  const setPlayingState = (title: string, value: boolean) => {
    setPlaying((previous) => {
      const next = new Set(previous);
      if (value) {
        next.add(title);
      } else {
        next.delete(title);
      }
      return next;
    });
  };

  const playVideo = (card: MockPromptCard) => {
    const video = videoRefs.current[card.title];
    if (video) {
      // jsdom's play() returns undefined (no Promise); real browsers
      // return a Promise. Guard so the mock preview never throws.
      const result = video.play() as unknown as
        | { catch: (handler: () => void) => void }
        | undefined;
      result?.catch(() => {
        /* Preview playback is best-effort in this mock preview. */
      });
      setPlayingState(card.title, true);
    }
  };

  const pauseVideo = (card: MockPromptCard) => {
    const video = videoRefs.current[card.title];
    if (video) {
      video.pause();
      video.currentTime = 0;
    }
    setPlayingState(card.title, false);
  };

  if (selected) {
    return (
      <section
        data-testid="prompt-detail"
        aria-label={`Details for ${selected.title}`}
        className="bg-canvas px-4 pb-12 sm:px-6 sm:pb-16"
      >
        <div className="mx-auto w-full max-w-5xl">
          <button
            type="button"
            data-testid="prompt-detail-back"
            onClick={() => setSelected(null)}
            className="text-sm font-semibold text-brand-gold"
          >
            ← Back to prompts
          </button>
          <h2 className="mt-4 text-3xl font-bold leading-tight text-ink">
            {selected.title}
          </h2>
          <p className="mt-2 text-sm text-ink-sub">
            <span className="font-semibold text-ink">{selected.tool}</span>
            {` · ${selected.category} · ${selected.language} · ${selected.length} · ${selected.format}`}
          </p>
          <video
            data-testid="prompt-detail-preview"
            src={selected.previewVideo}
            poster={selected.previewPoster}
            controls
            muted
            playsInline
            className="mt-6 h-60 w-full rounded-2xl border border-line bg-panel object-cover object-center"
          />
          <h3 className="mt-8 text-xl font-bold text-ink">Master prompt</h3>
          <p className="mt-3 rounded-2xl border border-line bg-panel p-4 text-sm leading-relaxed text-ink">
            {selected.masterPrompt}
          </p>
          <h3 className="mt-8 text-xl font-bold text-ink">
            How to make the video with it
          </h3>
          <ol className="mt-3 list-decimal space-y-2 pl-6 text-sm leading-relaxed text-ink-sub">
            {selected.howToSteps.map((step) => (
              <li key={step}>{step}</li>
            ))}
          </ol>
          <p className="mt-6 text-sm text-ink-sub">
            Sample master prompt and steps for preview only — mock data,
            not a real catalogue entry.
          </p>
        </div>
      </section>
    );
  }

  return (
    <section
      data-testid="prompt-mock-card-grid"
      aria-label="Prompt cards"
      className="bg-canvas px-4 pb-12 sm:px-6 sm:pb-16"
    >
      <div className="mx-auto grid w-full max-w-5xl grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
        {MOCK_PROMPT_CARDS.map((card) => {
          const isFavourite = favourites.has(card.title);
          const isPlaying = playing.has(card.title);
          return (
            <article
              key={card.title}
              data-testid="prompt-mock-card"
              onClick={() => setSelected(card)}
              className="cursor-pointer overflow-hidden rounded-2xl border border-line bg-panel shadow-card transition hover:-translate-y-1 hover:border-brand-gold hover:shadow-elevated"
            >
              <div
                data-testid="prompt-mock-card-preview"
                className="relative h-60 overflow-hidden"
                onMouseEnter={() => playVideo(card)}
                onMouseLeave={() => pauseVideo(card)}
              >
                <video
                  ref={(element) => {
                    videoRefs.current[card.title] = element;
                  }}
                  data-testid="prompt-mock-card-video"
                  src={card.previewVideo}
                  poster={card.previewPoster}
                  muted
                  loop
                  playsInline
                  preload="metadata"
                  className="h-full w-full object-cover object-center"
                />
                <button
                  type="button"
                  data-testid="prompt-mock-card-play"
                  aria-label={
                    isPlaying
                      ? `Pause preview for ${card.title}`
                      : `Play preview for ${card.title}`
                  }
                  onClick={(event) => {
                    event.stopPropagation();
                    if (isPlaying) {
                      pauseVideo(card);
                    } else {
                      playVideo(card);
                    }
                  }}
                  className="absolute left-1/2 top-1/2 flex size-12 -translate-x-1/2 -translate-y-1/2 items-center justify-center rounded-full bg-neutral-black/75 text-neutral-white"
                >
                  {isPlaying ? (
                    <PauseIcon aria-hidden className="size-6" />
                  ) : (
                    <PlayIcon aria-hidden className="size-6" />
                  )}
                </button>
                <button
                  type="button"
                  data-testid="prompt-mock-card-favourite"
                  aria-label={
                    isFavourite
                      ? `Saved ${card.title}`
                      : `Save ${card.title}`
                  }
                  aria-pressed={isFavourite}
                  onClick={(event) => {
                    event.stopPropagation();
                    toggleFavourite(card.title);
                  }}
                  className="absolute right-2 top-2 flex size-9 items-center justify-center rounded-full bg-neutral-black/75 text-neutral-white"
                >
                  <HeartIcon
                    aria-hidden
                    className={
                      isFavourite ? "size-5 text-brand-gold" : "size-5"
                    }
                    fill={isFavourite ? "currentColor" : "none"}
                  />
                </button>
                <span className="absolute bottom-2 right-2 rounded-sm bg-neutral-black/75 px-2 py-1 text-xs font-medium text-neutral-white">
                  {card.length}
                </span>
              </div>
              <div className="p-4">
                <h3 className="text-lg font-bold leading-snug text-ink">
                  {card.title}
                </h3>
                <p className="mt-2 text-sm leading-relaxed text-ink-sub">
                  {card.shortDescription}
                </p>
                <p className="mt-3 text-sm text-ink-sub">
                  <span className="font-semibold text-ink">{card.tool}</span>
                  {` · ${card.category} · ${card.language} · ${card.length} · ${card.format}`}
                </p>
                <p className="mt-3 border-t border-line pt-3 text-sm text-ink-sub">
                  {`Copied ${card.copiedCount} times · Added ${card.dateAdded}`}
                </p>
              </div>
            </article>
          );
        })}
      </div>
    </section>
  );
}
